// Pure-Rust core of MoltShield's adblock engine: wraps Brave's adblock-rust
// `Engine` with MoltBrowser's list preprocessing, resource vetting and
// stylesheet generation. Kept free of cxx types so it can be unit-tested and
// benchmarked with plain cargo (tools/shield_bench); molt_adblock.rs adapts
// it to C++.

use std::collections::HashSet;

use adblock::Engine;
use adblock::lists::{FilterSet, ParseOptions};
use adblock::request::Request;
use adblock::resources::{MimeType, PermissionMask, Resource, ResourceType};
use base64::Engine as _;

use crate::css;
use crate::preprocess::{self, PreprocessEnv};

/// Version of the adblock-rust crate this bridge is built against. The
/// serialized engine format is only guaranteed stable within one version, so
/// it is part of the on-disk cache key. Keep in sync with
/// //third_party/rust/chromium_crates_io/Cargo.toml.
pub const ADBLOCK_CRATE_VERSION: &str = "0.13.3";

/// Bumped whenever MoltBrowser changes how it builds engines (preprocessing,
/// permissions, …) so stale caches are rebuilt from list text.
pub const MOLT_ENGINE_FORMAT: u32 = 1;

/// Scriptlet permission granted to "trusted" lists (uBlock Origin's own
/// lists), allowing `trusted-*` scriptlets such as `trusted-set-cookie`.
/// Must match TRUSTED_PERMISSION in tools/shield_bench/gen_ubo_resources.mjs.
pub const TRUSTED_LIST_PERMISSION: PermissionMask = PermissionMask::from_bits(0b1);

/// Upper bound on the resources JSON accepted by `use_resources_json`.
pub const MAX_RESOURCES_JSON_BYTES: usize = 8 * 1024 * 1024;

/// Bounds on what a page may submit to `hidden_class_id_css` per call.
pub const MAX_CLASS_ID_TOKENS: usize = 5000;
pub const MAX_CLASS_ID_TOKEN_LEN: usize = 256;

/// Scriptlet resources bundled with the browser (uBlock Origin, pinned tag;
/// generated by tools/shield_bench/gen_ubo_resources.mjs).
pub const DEFAULT_RESOURCES_JSON: &str = include_str!("data/ubo_resources.json");

/// Small fallback list compiled when no downloaded lists are cached yet
/// (first run, or every download failed).
pub const BUILTIN_FILTER_LIST: &str = include_str!("data/builtin_filters.txt");

pub fn engine_format_key() -> String {
    format!("adblock-rust-{ADBLOCK_CRATE_VERSION}/molt-{MOLT_ENGINE_FORMAT}")
}

/// Accumulates filter lists before compiling them into a `ShieldEngine`.
pub struct EngineBuilder {
    set: FilterSet,
    env: PreprocessEnv,
    rule_lines: u32,
}

impl EngineBuilder {
    pub fn new(is_mobile: bool) -> Self {
        EngineBuilder {
            set: FilterSet::new(false),
            env: PreprocessEnv::molt(is_mobile),
            rule_lines: 0,
        }
    }

    /// Adds a list; returns the number of filter lines it contributed after
    /// preprocessing. `trusted` grants `trusted-*` scriptlets.
    pub fn add_list(&mut self, text: &str, trusted: bool) -> u32 {
        let processed = preprocess::preprocess(text, &self.env);
        let lines = preprocess::count_filter_lines(&processed);
        let permissions = if trusted { TRUSTED_LIST_PERMISSION } else { PermissionMask::default() };
        self.set.add_filter_list(
            processed.into_owned(),
            ParseOptions { permissions, ..ParseOptions::default() },
        );
        self.rule_lines = self.rule_lines.saturating_add(lines);
        lines
    }

    pub fn rule_lines(&self) -> u32 {
        self.rule_lines
    }

    pub fn build(self) -> ShieldEngine {
        crate::ensure_domain_resolver();
        ShieldEngine { engine: Engine::new_with_filter_set(self.set) }
    }
}

/// Outcome of a network request check.
#[derive(Debug, Default, Clone, PartialEq)]
pub struct CheckOutcome {
    /// A blocking (or `important`) filter matched.
    pub matched: bool,
    /// An `$important` filter matched: exceptions don't apply.
    pub important: bool,
    /// An exception (`@@`) filter matched.
    pub exception: bool,
    /// Final verdict.
    pub should_block: bool,
    /// `data:` URL to serve instead of the resource (`$redirect`), if any.
    pub redirect: Option<String>,
    /// URL with `$removeparam` parameters stripped, if it changed.
    pub rewritten_url: Option<String>,
}

/// Cosmetic resources for a document URL.
#[derive(Debug, Default, Clone)]
pub struct CosmeticOutcome {
    /// `sel{display:none!important}` rules (hostname-specific + generic
    /// complex selectors), vetted by `css::is_safe_selector`.
    pub hide_css: String,
    /// Scriptlet bundle to run in the page's main world at document start,
    /// wrapped in an IIFE. Empty if there's nothing to inject.
    pub injected_script: String,
    /// `$generichide`: don't query generic class/id rules for this page.
    pub generichide: bool,
    /// Procedural/action filters (`:has-text()`, `:remove()`, …) matched for
    /// this URL. MoltShield doesn't execute them yet; reported for stats.
    pub procedural_count: u32,
}

pub struct ShieldEngine {
    engine: Engine,
}

impl ShieldEngine {
    pub fn empty() -> Self {
        crate::ensure_domain_resolver();
        ShieldEngine { engine: Engine::default() }
    }

    pub fn serialize(&self) -> Vec<u8> {
        self.engine.serialize()
    }

    /// Replaces this engine's filters with a serialized engine. Resources set
    /// with `use_resources_json` are kept. Returns false (engine unchanged)
    /// on a corrupt or version-mismatched blob.
    pub fn deserialize(&mut self, data: &[u8]) -> bool {
        crate::ensure_domain_resolver();
        self.engine.deserialize(data).is_ok()
    }

    /// Loads scriptlet/redirect resources (adblock-rust `Resource` JSON).
    /// Returns how many were accepted; 0 leaves the current set in place.
    ///
    /// Legacy *template* scriptlets are refused: adblock-rust substitutes
    /// their `{{N}}` placeholders with arguments that are escaped for a
    /// double-quoted context only, so a template that quotes `'{{1}}'` would
    /// let a filter argument break out into script. Function-style resources
    /// (all of uBO's current ones) are invoked as `fn("arg", …)` with
    /// JSON-escaped arguments and are safe.
    pub fn use_resources_json(&mut self, json: &str) -> usize {
        if json.len() > MAX_RESOURCES_JSON_BYTES {
            return 0;
        }
        let parsed: Vec<Resource> = match serde_json::from_str(json) {
            Ok(v) => v,
            Err(_) => return 0,
        };
        let accepted: Vec<Resource> = parsed.into_iter().filter(is_acceptable_resource).collect();
        let n = accepted.len();
        if n > 0 {
            self.engine.use_resources(accepted);
        }
        n
    }

    /// Checks one request. `url` must be a canonical (GURL-serialized) URL;
    /// `hostname`/`source_hostname` are the request and initiator hosts;
    /// `third_party` is computed by the caller with Chromium's
    /// registry-controlled-domain rules.
    pub fn check(
        &self,
        url: &str,
        hostname: &str,
        source_hostname: &str,
        request_type: &str,
        third_party: bool,
        method: &str,
    ) -> CheckOutcome {
        let request =
            Request::preparsed(url, hostname, source_hostname, request_type, third_party, method);
        let r = self.engine.check_network_request(&request);
        CheckOutcome {
            matched: r.filter.is_some(),
            important: r.important,
            exception: r.exception.is_some(),
            should_block: r.should_block(),
            redirect: r.redirect.filter(|d| d.starts_with("data:")),
            rewritten_url: r.rewritten_url,
        }
    }

    pub fn cosmetic(&self, url: &str) -> CosmeticOutcome {
        let r = self.engine.url_cosmetic_resources(url);
        let mut selectors: Vec<&str> = r.hide_selectors.iter().map(String::as_str).collect();
        selectors.sort_unstable();
        CosmeticOutcome {
            hide_css: css::hide_stylesheet(selectors),
            injected_script: wrap_scriptlets(&r.injected_script),
            generichide: r.generichide,
            procedural_count: u32::try_from(r.procedural_actions.len()).unwrap_or(u32::MAX),
        }
    }

    /// CSS hiding elements matched by generic `##.class` / `###id` rules,
    /// given classes and ids seen in a document at `url`. Honors the page's
    /// `#@#` exceptions and `$generichide`.
    pub fn hidden_class_id_css<'a>(
        &self,
        url: &str,
        classes: impl IntoIterator<Item = &'a str>,
        ids: impl IntoIterator<Item = &'a str>,
    ) -> String {
        let r = self.engine.url_cosmetic_resources(url);
        if r.generichide {
            return String::new();
        }
        let classes = bounded_tokens(classes);
        let ids = bounded_tokens(ids);
        let selectors = self.engine.hidden_class_id_selectors(classes, ids, &r.exceptions);
        let unique: HashSet<&str> = selectors.iter().map(String::as_str).collect();
        let mut sorted: Vec<&str> = unique.into_iter().collect();
        sorted.sort_unstable();
        css::hide_stylesheet(sorted)
    }
}

/// Page-supplied class/id tokens, bounded in count and length.
fn bounded_tokens<'a>(tokens: impl IntoIterator<Item = &'a str>) -> Vec<&'a str> {
    tokens
        .into_iter()
        .filter(|t| !t.is_empty() && t.len() <= MAX_CLASS_ID_TOKEN_LEN)
        .take(MAX_CLASS_ID_TOKENS)
        .collect()
}

fn is_acceptable_resource(r: &Resource) -> bool {
    match &r.kind {
        ResourceType::Template => false,
        ResourceType::Mime(MimeType::ApplicationJavascript) => {
            match base64::engine::general_purpose::STANDARD.decode(r.content.as_bytes()) {
                Ok(bytes) => !bytes.windows(5).any(|w| w == b"{{1}}"),
                Err(_) => false,
            }
        }
        _ => true,
    }
}

/// Wraps adblock-rust's scriptlet bundle for main-world injection. uBO's
/// helpers (safe-self.fn etc.) read a `scriptletGlobals` object that uBO's
/// own injector defines; the IIFE keeps all helper names off `window`.
fn wrap_scriptlets(script: &str) -> String {
    if script.trim().is_empty() {
        return String::new();
    }
    let mut out = String::with_capacity(script.len() + 96);
    out.push_str("(function() {\n'use strict';\nconst scriptletGlobals = {};\n");
    out.push_str(script);
    out.push_str("\n})();\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn engine_with(list: &str) -> ShieldEngine {
        let mut b = EngineBuilder::new(false);
        b.add_list(list, false);
        let mut e = b.build();
        assert!(e.use_resources_json(DEFAULT_RESOURCES_JSON) > 100);
        e
    }

    fn check(e: &ShieldEngine, url: &str, src_host: &str, ty: &str, tp: bool) -> CheckOutcome {
        let host = url.split('/').nth(2).unwrap_or("");
        e.check(url, host, src_host, ty, tp, "GET")
    }

    #[test]
    fn blocks_and_excepts() {
        let e = engine_with(
            "||ads.example^\n@@||ads.example/allowed.js$script\n||tracker.example^$third-party\n",
        );
        let r = check(&e, "https://ads.example/banner.js", "news.test", "script", true);
        assert!(r.matched && r.should_block && !r.exception);
        let r = check(&e, "https://ads.example/allowed.js", "news.test", "script", true);
        assert!(r.matched && r.exception && !r.should_block);
        // $third-party respected.
        assert!(!check(&e, "https://tracker.example/t.js", "tracker.example", "script", false)
            .should_block);
        assert!(check(&e, "https://tracker.example/t.js", "news.test", "script", true)
            .should_block);
    }

    #[test]
    fn important_beats_exception() {
        let e = engine_with("||t.example^$important\n@@||t.example^\n");
        let r = check(&e, "https://t.example/x", "a.test", "xmlhttprequest", true);
        assert!(r.important && r.should_block);
    }

    #[test]
    fn redirect_resource_is_data_url() {
        let e = engine_with("||g.example/analytics.js$script,redirect=noop.js\n");
        let r = check(&e, "https://g.example/analytics.js", "a.test", "script", true);
        assert!(r.should_block);
        let d = r.redirect.expect("redirect");
        assert!(d.starts_with("data:application/javascript;base64,"));
    }

    #[test]
    fn removeparam_rewrites() {
        let e = engine_with("$removeparam=utm_source\n");
        let r = check(&e, "https://a.test/p?utm_source=x&id=1", "a.test", "xmlhttprequest", false);
        assert_eq!(r.rewritten_url.as_deref(), Some("https://a.test/p?id=1"));
        assert!(!r.should_block);
    }

    #[test]
    fn serialize_roundtrip() {
        let e = engine_with("||ads.example^\nexample.com##.sponsored\n");
        let blob = e.serialize();
        let mut e2 = ShieldEngine::empty();
        assert!(e2.deserialize(&blob));
        assert!(check(&e2, "https://ads.example/x", "a.test", "image", true).should_block);
        assert!(e2.cosmetic("https://example.com/").hide_css.contains(".sponsored"));
        // Garbage is rejected without disturbing the engine.
        assert!(!e2.deserialize(b"not an engine"));
        assert!(check(&e2, "https://ads.example/x", "a.test", "image", true).should_block);
    }

    #[test]
    fn cosmetic_and_scriptlets() {
        let e = engine_with(
            "example.com##.sponsored\nexample.com##+js(set-constant, ads.enabled, false)\n\
             ##.generic-ad\nexample.com#@#.generic-ad\n",
        );
        let c = e.cosmetic("https://www.example.com/page");
        assert!(c.hide_css.contains(".sponsored{display:none!important}"));
        assert!(c.injected_script.contains("scriptletGlobals"));
        assert!(c.injected_script.contains("setConstant("));
        assert!(!c.generichide);
        // Generic class rule applies elsewhere but is excepted on example.com.
        assert!(e
            .hidden_class_id_css("https://other.test/", ["generic-ad"], [])
            .contains(".generic-ad"));
        assert!(e.hidden_class_id_css("https://example.com/", ["generic-ad"], []).is_empty());
        // Nothing to inject elsewhere.
        assert!(e.cosmetic("https://other.test/").injected_script.is_empty());
    }

    #[test]
    fn scriptlet_arguments_are_json_escaped() {
        // The old matcher spliced args into JS verbatim. adblock-rust must
        // keep a quote in an argument inside the string literal.
        let e = engine_with("example.com##+js(set-constant, foo, x\"});alert(1);//)\n");
        let script = e.cosmetic("https://example.com/").injected_script;
        assert!(
            script.contains(r#"setConstant("foo", "x\"});alert(1);//")"#),
            "{script}"
        );
    }

    #[test]
    fn trusted_scriptlets_need_trusted_list() {
        let rule = "example.com##+js(trusted-set-cookie, a, b)\n";
        let untrusted = engine_with(rule);
        assert!(untrusted.cosmetic("https://example.com/").injected_script.is_empty());
        let mut b = EngineBuilder::new(false);
        b.add_list(rule, true);
        let mut trusted = b.build();
        trusted.use_resources_json(DEFAULT_RESOURCES_JSON);
        assert!(trusted.cosmetic("https://example.com/").injected_script.contains("trusted"));
    }

    #[test]
    fn generichide_suppresses_generic_rules() {
        let e = engine_with("##.generic-ad\n@@||nogeneric.test^$generichide\n");
        assert!(e.cosmetic("https://nogeneric.test/").generichide);
        assert!(e.hidden_class_id_css("https://nogeneric.test/", ["generic-ad"], []).is_empty());
    }

    #[test]
    fn rejects_unsafe_resources() {
        let mut e = ShieldEngine::empty();
        let tmpl = base64::engine::general_purpose::STANDARD.encode("var x = '{{1}}';");
        let json = format!(
            "[{{\"name\":\"evil.js\",\"aliases\":[],\"kind\":{{\"mime\":\"application/javascript\"}},\"content\":\"{tmpl}\"}},\
              {{\"name\":\"tmpl.js\",\"aliases\":[],\"kind\":\"template\",\"content\":\"{tmpl}\"}}]"
        );
        assert_eq!(e.use_resources_json(&json), 0);
        assert_eq!(e.use_resources_json("not json"), 0);
    }

    #[test]
    fn builtin_list_compiles_and_blocks() {
        let e = engine_with(BUILTIN_FILTER_LIST);
        assert!(check(&e, "https://securepubads.g.doubleclick.net/tag/js/gpt.js", "news.test",
                      "script", true).should_block);
        assert!(!check(&e, "https://www.example.org/app.js", "www.example.org", "script", false)
            .should_block);
    }

    #[test]
    fn untrusted_class_tokens_are_bounded() {
        let e = engine_with("##.ad\n");
        let long = "a".repeat(MAX_CLASS_ID_TOKEN_LEN + 1);
        assert!(e.hidden_class_id_css("https://x.test/", [long.as_str()], []).is_empty());
        let css = e.hidden_class_id_css("https://x.test/", ["ad", "ad", "zzz"], []);
        assert_eq!(css, ".ad{display:none!important}\n");
    }
}
