"""Buildflag headers: finds the buildflag_header() target that writes each
missing header, evaluates its flags with the GN reader (args from
configs/linux-x64.gn, defaults from the declare_args() they come from) and
runs the real writer script (build/write_buildflag_header.py, or
PartitionAlloc's own).

A header is made again when what decides its flags may have changed
(refresh): the platform's GN args file, any GN file of MoltBrowser's
overlay (where its declare_args() and features live), the header's own
BUILD.gn, or the pin. Its flags are then evaluated again and the header is
rewritten if they differ (buildflag_stamps.json). Headers made before
stamps are found by the label the writers put in their second line."""
import hashlib
import json
import re
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

from .sources import REPO_ROOT, log

TEMPLATES = ("buildflag_header", "pa_buildflag_header")

# Flags whose GN value the reader cannot compute (exec_script, ...), with the
# value the Linux official build gets.
OVERRIDES = {}

STAMPS = "buildflag_stamps.json"
# Bump when how headers are written changes.
DRIVER_VERSION = "1"

# The writers' first lines: '// Generated by ...write_buildflag_header.py'
# then '// From "//dir:target"'.
_FROM_RE = re.compile(rb'^// Generated by \S*write_buildflag_header\.py\n'
                      rb'// From "(//[^":]*):([^"]+)"')


def _header_path(t):
    hdr = t.get("header")
    if not isinstance(hdr, str):
        return None
    hd = t.get("header_dir")
    if isinstance(hd, str):
        return hd.strip("/") + "/" + hdr
    return t.path[2:] + "/" + hdr


def _candidates(name, include_dirs):
    parts = name.split("/")
    dirs = []
    for inc in include_dirs:
        if inc.startswith("gen:"):
            continue
        for i in range(len(parts) - 1, 0, -1):
            d = "/".join(parts[:i])
            dirs.append((inc + "/" + d) if inc else d)
    return list(dict.fromkeys(dirs))


def _values(t):
    """(["NAME=value", ...], [unknown names]) of a target's flags, or
    (None, reason)."""
    flags = t.get("flags") or []
    if not isinstance(flags, list):
        return None, "flags not computable"
    vals = []
    unknown = []
    for f in flags:
        if not isinstance(f, str) or "=" not in f:
            unknown.append(repr(f))
            continue
        k, v = f.split("=", 1)
        if k in OVERRIDES:
            v = OVERRIDES[k]
        if "<UNKNOWN>" in v:
            unknown.append(k)
            v = "0"
        vals.append("%s=%s" % (k, v))
    return vals, unknown


def _write(tree, gen_dir, name, t, d):
    """Runs the writer for target `t` (in directory `d`). Returns None on
    success, else a reason."""
    vals, unknown = _values(t)
    if vals is None:
        return unknown
    if unknown:
        log("buildflags: %s: unknown value(s) for %s (set to 0)" % (
            name, ", ".join(unknown)))
    script = ("base/allocator/partition_allocator/src/partition_alloc/"
              "write_buildflag_header.py"
              if t.func == "pa_buildflag_header"
              else "build/write_buildflag_header.py")
    tree.materialize([script])
    with tempfile.NamedTemporaryFile("w", suffix=".rsp",
                                     delete=False) as rsp:
        rsp.write(" ".join(shlex.quote(x) for x in ["--flags"] + vals))
    out = Path(gen_dir) / name
    out.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run(
        [sys.executable, "-I", str(tree.local_path(script)),
         "--output", name, "--rulename", "//%s:%s" % (d, t.name),
         "--gen-dir", str(gen_dir), "--definitions", rsp.name],
        capture_output=True, text=True)
    Path(rsp.name).unlink()
    if r.returncode != 0:
        return "writer failed: " + r.stderr[-300:]
    if unknown:
        with open(out, "a") as f:
            f.write("// compile_check: unknown GN values set to 0: %s\n"
                    % ", ".join(unknown))
    return None


def _platform_key(tree):
    """What decides every header's flags besides its own BUILD.gn: the pin,
    the platform's args, and MoltBrowser's GN files."""
    plat = tree.platform
    h = hashlib.sha1(DRIVER_VERSION.encode())
    h.update(("%s\0%s\0%s\0" % (
        tree.chromium.rev, plat.name,
        json.dumps(plat.extra_args, sort_keys=True))).encode())
    try:
        h.update((REPO_ROOT / plat.args_file).read_bytes())
    except OSError:
        h.update(b"-")
    for p in sorted(x for x in tree.overlay_set()
                    if x.endswith((".gn", ".gni"))):
        h.update(p.encode() + b"\0")
        h.update(hashlib.sha1(tree.read(p) or b"").digest())
    return h.hexdigest()


def _key(tree, pkey, bf):
    h = hashlib.sha1(pkey.encode())
    h.update(hashlib.sha1(tree.read(bf) or b"").digest())
    return h.hexdigest()


def _load(tree):
    try:
        return json.loads((Path(tree.state) / STAMPS).read_text())
    except (OSError, ValueError):
        return {}


def _save(tree, stamps):
    Path(tree.state).mkdir(parents=True, exist_ok=True)
    (Path(tree.state) / STAMPS).write_text(json.dumps(stamps, indent=1,
                                                      sort_keys=True))


def generated_headers(gen_dir):
    """{gen-relative name: (dir, target)} of every buildflag header in
    gen_dir, from the label its writer put in it."""
    out = {}
    gen_dir = Path(gen_dir)
    if not gen_dir.is_dir():
        return out
    for f in gen_dir.rglob("*.h"):
        try:
            with open(f, "rb") as fh:
                head = fh.read(400)
        except OSError:
            continue
        m = _FROM_RE.match(head)
        if m:
            out[str(f.relative_to(gen_dir))] = (m.group(1).decode()[2:],
                                                m.group(2).decode())
    return out


def refresh(tree, interp, gen_dir):
    """Writes again every buildflag header whose flags may have changed
    since it was written (see the module doc), when they did. Returns
    (remade, removed)."""
    stamps = _load(tree)
    pkey = _platform_key(tree)
    remade, removed = [], []
    for name, (d, tname) in sorted(generated_headers(gen_dir).items()):
        bf = (d + "/BUILD.gn") if d else "BUILD.gn"
        key = _key(tree, pkey, bf)
        if stamps.get(name) == key:
            continue
        out = Path(gen_dir) / name
        t = None
        if tree.exists(bf):
            t = next((x for x in interp.run_file("//" + bf)
                      if x.func in TEMPLATES and x.name == tname and
                      _header_path(x) is not None), None)
        if t is None:
            log("buildflags: %s: //%s:%s is gone; removed" % (name, d,
                                                               tname))
            out.unlink()
            stamps.pop(name, None)
            removed.append(name)
            continue
        before = out.read_bytes()
        err = _write(tree, gen_dir, name, t, d)
        if err:
            log("buildflags: %s: %s; removed" % (name, err))
            if out.exists():
                out.unlink()
            stamps.pop(name, None)
            removed.append(name)
            continue
        if out.read_bytes() != before:
            remade.append(name)
        stamps[name] = key
    _save(tree, stamps)
    return remade, removed


def generate(tree, interp, gen_dir, names, include_dirs):
    """Writes gen_dir/<name> for every name it can; returns (written,
    {name: reason})."""
    gen_dir = Path(gen_dir)
    found = {}
    for name in names:
        for d in _candidates(name, include_dirs):
            if not tree.exists(d + "/BUILD.gn"):
                continue
            for t in interp.run_file("//" + d + "/BUILD.gn"):
                if t.func not in TEMPLATES:
                    continue
                hp = _header_path(t)
                if hp is None:
                    continue
                for inc in include_dirs:
                    if inc.startswith("gen:"):
                        continue
                    pre = (inc + "/") if inc else ""
                    if hp == pre + name or (not inc and hp == name):
                        found[name] = (t, d)
            if name in found:
                break
    written, failed = [], {}
    stamps = _load(tree) if hasattr(tree, "state") else None
    pkey = _platform_key(tree) if stamps is not None else None
    for name in names:
        if name not in found:
            failed[name] = "no buildflag_header() target found"
            continue
        t, d = found[name]
        err = _write(tree, gen_dir, name, t, d)
        if err:
            failed[name] = err
            continue
        written.append(name)
        if stamps is not None:
            stamps[name] = _key(tree, pkey,
                                (d + "/BUILD.gn") if d else "BUILD.gn")
    if stamps is not None and written:
        _save(tree, stamps)
    return written, failed
