def cxx_u16_literal(text):
    out = []
    for ch in text:
        cp = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        elif cp <= 0xFFFF:
            out.append("\\u%04X" % cp)
        else:
            out.append("\\U%08X" % cp)
    return 'u"' + "".join(out) + '"'


def wrap_literal(prefix, text, width):
    """`text` (a C++ string literal's contents, already escaped) as adjacent
    literals of at most `width` columns, split after spaces."""
    chunks, current = [], ""
    for word in re.split(r"(?<= )", text):
        if current and len(prefix) + len(current) + len(word) + 2 > width:
            chunks.append(current)
            current = ""
        current += word
    chunks.append(current)
    return ['%s"%s"' % (prefix, c) for c in chunks]


def cxx_literal_lines(prefix, text, width):
    """A u"" literal (prefix "u") or "" literal (prefix "") of `text`,
    wrapped to `width` columns."""
    literal = cxx_u16_literal(text) if prefix == "u" else '"%s"' % text
    body = literal[len(prefix) + 1:-1]
    return wrap_literal(prefix, body, width)


def emit_initializer(lines, indent, fields, width=80):
    """Appends `{f1, f2, ...},` at `indent`, on one line if it fits, else
    one field per line (each field a list of lines, already wrapped)."""
    flat = [f[0] for f in fields if len(f) == 1]
    if len(flat) == len(fields):
        one = "%s{%s}," % (indent, ", ".join(flat))
        if len(one) <= width:
            lines.append(one)
            return
    inner = indent + " "
    for i, field in enumerate(fields):
        last = i == len(fields) - 1
        for j, part in enumerate(field):
            lead = (indent + "{") if (i == 0 and j == 0) else inner
            tail = ("}," if last else ",") if j == len(field) - 1 else ""
            lines.append(lead + part + tail)


def emit_comment(lines, indent, text, width=80):
    current = ""
    for word in text.split():
        if current and len(indent) + 3 + len(current) + 1 + len(word) > width:
            lines.append("%s// %s" % (indent, current))
            current = word
        else:
            current = (current + " " + word).strip()
    if current:
        lines.append("%s// %s" % (indent, current))


def strings_table(src, pin_version):
    messages = {}
    for path in (BLINK_STRINGS, PERMISSION_STRINGS):
        messages.update(grd_messages(src.read(path)))

    errors = []
    pinned_names = [n for n, _ in PINNED_STRINGS]
    if len(set(pinned_names)) != len(pinned_names):
        errors.append("PINNED_STRINGS lists a message twice")
    for name in sorted(messages):
        pinned = name in pinned_names
        localized = name in LOCALIZED_STRINGS or any(
            name.startswith(p) for p in LOCALIZED_PREFIXES)
        if pinned and localized:
            errors.append("%s is both pinned and left localized" % name)
        elif not pinned and not localized:
            errors.append(
                "%s is new: decide whether pages can read it and add it to "
                "PINNED_STRINGS or LOCALIZED_STRINGS" % name)
    for name in pinned_names:
        if name not in messages:
            errors.append("%s is no longer in the .grd files" % name)
        elif messages[name][1]:
            errors.append("%s is platform-dependent now (inside an <if>)"
                          % name)
    for name in LOCALIZED_STRINGS:
        if name not in messages:
            errors.append("%s (LOCALIZED_STRINGS) is no longer in the .grd "
                          "files" % name)
    if errors:
        die("\n  ".join(["the string classification is out of date:"] +
                        errors))

    lines = [
        "// Copyright 2026 GenEye AI Labs Inc.",
        "// Licensed under GPLv3. See LICENSE file.",
        "//",
        "// GENERATED by tools/moltnet_locale/generate_tables.py from",
        "// %s and" % BLINK_STRINGS,
        "// %s" % PERMISSION_STRINGS,
        "// at Chromium %s. Do not edit; change the script and rerun it with"
        % pin_version,
        "// --write.",
        "",
        '#include "chrome/renderer/molt_ai/fingerprinting/'
        'moltnet_locale_strings.h"',
        "",
        "#include <array>",
        "",
        '#include "third_party/blink/public/strings/grit/blink_strings.h"',
        '#include "third_party/blink/public/strings/grit/'
        'permission_element_strings.h"',
        "",
        "namespace molt_ai::fingerprinting {",
        "",
        "namespace {",
        "",
        "constexpr auto kMoltNetLocaleStrings = "
        "std::to_array<MoltNetLocaleString>({",
    ]
    previous = None
    indent = "    "
    for name, why in PINNED_STRINGS:
        text = messages[name][0]
        comment = why if why else (
            "Pages can't read it: the picker popup, kept all English.")
        if comment != previous:
            emit_comment(lines, indent, comment)
            previous = comment
        emit_initializer(lines, indent, [
            [name],
            ['"%s"' % name],
            cxx_literal_lines("u", text, 80 - len(indent) - 2),
            ["/*page_observable=*/%s" % ("true" if why else "false")],
        ])
    lines += [
        "});",
        "",
        "}  // namespace",
        "",
        "base::span<const MoltNetLocaleString> MoltNetLocaleStrings() {",
        "  return kMoltNetLocaleStrings;",
        "}",
        "",
        "}  // namespace molt_ai::fingerprinting",
        "",
    ]
    return "\n".join(lines)


