# Reading .grd files


class GrdSource:
    def __init__(self, args):
        self.grd_root = Path(args.grd_root) if args.grd_root else None
        self.upstream = None
        self.commit = None
        if not self.grd_root:
            import upstream as up
            pin = up.read_pin()
            self.upstream = up.Upstream(
                cache_dir=args.cache or up.DEFAULT_CACHE, offline=args.offline)
            self.commit = self.upstream.resolve(pin.revision)

    def read(self, path):
        if self.grd_root:
            p = self.grd_root / path
            if not p.is_file():
                die("%s not found" % p)
            return p.read_bytes()
        data = self.upstream.read(self.commit, path)
        if data is None:
            die("%s not found at the pinned revision" % path)
        return data


def message_text(message):
    """A grit message's text as grit puts it in an en-US .pak: each
    placeholder replaced by its original text ($1, ...), examples dropped,
    leading and trailing whitespace stripped (''' keeps it)."""
    parts = [message.text or ""]
    for child in message:
        if child.tag == "ph":
            parts.append(child.text or "")
        else:
            die("%s: unexpected <%s> in a message"
                % (message.get("name"), child.tag))
        parts.append(child.tail or "")
    text = "".join(parts).strip()
    if text.startswith("'''"):
        text = text[3:]
    if text.endswith("'''"):
        text = text[:-3]
    return text


def grd_messages(data):
    """{name: (text, conditional)}: conditional is True for a message inside
    an <if>, whose text depends on the platform."""
    root = ET.fromstring(data)
    out = {}

    def walk(node, conditional):
        for child in node:
            if child.tag == "message":
                name = child.get("name")
                if name in out and not (conditional and out[name][1]):
                    die("%s defined twice" % name)
                out[name] = (message_text(child), conditional)
            elif child.tag in ("release", "messages", "if", "then", "else"):
                walk(child, conditional or child.tag in ("if", "then", "else"))

    walk(root, False)
    return out


