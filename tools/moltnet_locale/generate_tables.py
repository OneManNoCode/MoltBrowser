# The font table


def norm_font(name):
    """fonts.h's FontName normalization for ASCII names: ASCII letters
    lower-cased, ASCII whitespace dropped."""
    return "".join(c.lower() if "A" <= c <= "Z" else c for c in name
                   if c not in " \t\n\r\f\v")


def font_allowlists():
    src = FONT_ALLOWLISTS.read_text()
    lists = {}
    for platform, body in re.findall(
            r"constexpr FontListEntry k(\w+)Fonts\[\] = \{(.*?)\n\};", src,
            re.S):
        entries = {}
        for name, alias in re.findall(
                r'\{"([^"]*)"(?:,\s*"([^"]*)")?\}', body):
            entries[norm_font(name)] = alias
        lists[platform] = entries
    for platform in LOCALE_SETTINGS:
        if not lists.get(platform):
            die("no %s list in %s" % (platform, FONT_ALLOWLISTS))
    return lists


def resolve_font(value, allowlist):
    """The family MoltNet uses for a default whose en-US value is `value`:
    the first family of the list (Chromium's ",A,B,C" form) or the single
    family that the OS installs by default (the allow-list), an alias
    replaced by the family it stands for; "" when none is."""
    families = [f for f in value.split(",") if f] \
        if value.startswith(",") else [value]
    for family in families:
        key = norm_font(family)
        if key in allowlist:
            alias_of = allowlist[key]
            return alias_of if alias_of else family
    return ""


def font_pref(message):
    m = re.match(r"^IDS_(STANDARD|FIXED|SERIF|SANS_SERIF|CURSIVE|FANTASY|MATH)"
                 r"_FONT_FAMILY(_[A-Z_]+)?$", message)
    if not m or (m.group(2) or "") not in SCRIPTS:
        return None
    return "%s%s.%s" % (PREF_PREFIX, GENERIC_FAMILIES[m.group(1)],
                        SCRIPTS[m.group(2) or ""])


