def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write", action="store_true",
                        help="rewrite the generated files")
    parser.add_argument("--grd-root",
                        help="read the .grd files from this directory")
    parser.add_argument("--cache", help="the upstream cache directory")
    parser.add_argument("--offline", action="store_true",
                        help="don't fetch, use the upstream cache only")
    args = parser.parse_args()

    import upstream as up
    pin = up.read_pin()
    src = GrdSource(args)
    outputs = [
        (STRINGS_TABLE, strings_table(src, pin.version)),
        (PREFS_TABLE, prefs_table(src, pin.version)),
    ]
    stale = []
    for path, text in outputs:
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        if args.write:
            path.write_text(text)
            print("wrote %s" % path.relative_to(REPO_ROOT))
        else:
            stale.append(path.relative_to(REPO_ROOT))
    if stale:
        print("out of date (run tools/moltnet_locale/generate_tables.py "
              "--write): " + ", ".join(str(p) for p in stale),
              file=sys.stderr)
        return 1
    if not args.write:
        print("MoltNet locale tables match Chromium %s" % pin.version)
    return 0


if __name__ == "__main__":
    sys.exit(main())
