"""Turn the upstream-file copies in src/ into a patch series.

For every file under src/ that also exists in Chromium at the pinned
revision (chromium_version.txt), write patches/<path>.patch: a git-format
unified diff from upstream@pin to our copy (binary-safe, a/ b/ paths relative
to chromium/src, applies with `git apply -p1`). patches/series lists them in
order. Also written:

  patches/identical.txt   overlay files byte-identical to upstream@pin.
                          They change nothing today, but after a rebase they
                          would silently REVERT upstream changes; drop them
                          from src/ once the patch flow is the default.
  patches/whole_files.txt upstream files that live in a DEPS subproject (a
                          separate repo the mirror cannot diff); they stay
                          whole-file overlays.

First-party files (not in upstream) are not touched; they stay as files.
src/ remains the source of truth until the build switches to the series:
re-run this after changing an upstream file in src/ and check the result
with tools/chromium/verify_patches.py.

Usage:
  tools/chromium/overlay_to_patches.py [--cache DIR] [--remote URL] [--offline]
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import upstream as up  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--cache", default=str(up.DEFAULT_CACHE))
    ap.add_argument("--remote", default=up.DEFAULT_REMOTE)
    ap.add_argument("--offline", action="store_true",
                    help="use only what is already in the cache")
    args = ap.parse_args()

    pin = up.read_pin()
    chromium = up.Upstream(args.cache, args.remote, args.offline)
    commit = chromium.resolve(pin.revision)
    actual_version = chromium.version(commit)
    if actual_version != pin.version:
        up.die("chrome/VERSION at %s is %s, but chromium_version.txt says %s"
               % (pin.revision, actual_version, pin.version))
    up.log("Upstream base: %s" % pin)

    kinds = up.classify(chromium, commit)
    by_kind = {}
    for path, kind in kinds.items():
        by_kind.setdefault(kind, []).append(path)
    patched = sorted(by_kind.get(up.PATCHED, []))
    identical = sorted(by_kind.get(up.IDENTICAL_KIND, []))
    deps = sorted(by_kind.get(up.DEPS_FILE, []))

    tree = chromium.tree(commit)
    bases = chromium.blobs(tree[p].oid for p in patched)

    up.PATCHES_DIR.mkdir(exist_ok=True)
    wanted = set()
    for path in patched:
        base = bases[tree[path].oid]
        diff = up.make_diff(path, base, up.overlay_bytes(path),
                            up.overlay_mode(path))
        if not diff:
            up.die("%s classified as patched but the diff is empty" % path)
        out = up.PATCHES_DIR / (path + up.PATCH_SUFFIX)
        out.parent.mkdir(parents=True, exist_ok=True)
        data = up.patch_header(path, pin) + diff
        if not out.exists() or out.read_bytes() != data:
            out.write_bytes(data)
        wanted.add(out)

    # Drop patches for files that are no longer patched.
    stale = [p for p in up.PATCHES_DIR.rglob("*" + up.PATCH_SUFFIX)
             if p not in wanted]
    for p in stale:
        p.unlink()
    for d in sorted({p.parent for p in stale}, key=lambda d: -len(d.parts)):
        while d != up.PATCHES_DIR and d.exists() and not any(d.iterdir()):
            d.rmdir()
            d = d.parent

    header = ("# Generated by tools/chromium/overlay_to_patches.py - do not "
              "edit.\n# Upstream base: chromium/src@%s (%s)\n"
              % (pin.revision, pin.version))
    up.SERIES.write_text(
        header + "# Apply from chromium/src with: git apply -p1 <patch>\n"
        + "".join(p + up.PATCH_SUFFIX + "\n" for p in patched))
    up.IDENTICAL.write_text(
        header + "# Overlay files byte-identical to upstream at the base "
        "above. Safe to drop\n# from src/; left in place they REVERT "
        "upstream changes after a rebase.\n"
        + "".join(p + "\n" for p in identical))
    up.WHOLE_FILES.write_text(
        header + "# Upstream files inside DEPS subprojects (separate repos): "
        "kept as whole-file\n# overlays, not diffed. Check them by hand on "
        "every rebase.\n"
        + "".join("%s\t# %s@%s\n" % ((p,) + chromium.gitlink_for(commit, p))
                  for p in deps))

    first_party = len(by_kind.get(up.FIRST_PARTY, []))
    print("Upstream base:      %s" % pin)
    print("Overlay files:      %d" % len(kinds))
    print("  patched:          %d  -> patches/<path>.patch (patches/series)"
          % len(patched))
    print("  identical:        %d  -> patches/identical.txt (droppable)"
          % len(identical))
    print("  DEPS subproject:  %d  -> patches/whole_files.txt" % len(deps))
    print("  first-party:      %d  (not upstream; stay as files)"
          % first_party)
    if stale:
        print("Removed %d stale patch file(s)." % len(stale))
    if identical:
        print("\nIdentical to upstream (can be dropped from src/ later):")
        for p in identical:
            print("  src/" + p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
