"""DEPS subprojects: the upstream side of patches/whole_files.txt.

Some upstream files MoltBrowser changes live in a DEPS subproject (V8, Skia,
WebRTC, the search engine definitions, ...): a separate repository that
chromium/src only points at (a gitlink, the commit DEPS pins). The mirror
can't diff them, so src/ keeps them as whole files, and
patches/whole_files.txt records, for each, the subproject commit it was last
merged with, and the Chromium release whose DEPS pinned it:

  v8/src/base/ieee754.cc<TAB># v8@392e44423f46...(40 hex) (156.0.8078.48)

That commit, not the pin's, is the merge base. When a rebase moves the
subproject, a whole file left as it was would silently revert every upstream
change to it, so tools/chromium/rebase.py 3-way merges each one (base: the
recorded commit; theirs: the new gitlink) and --apply records the new commit;
verify_patches.py fails while any whole file is behind the pin's gitlink.

Upstream content comes from, in order:
  1. the subproject's GitHub mirror (MIRRORS), a bare, shallow, blob-less
     clone under <cache>/deps/ (git checks the commit ids), when the mirror
     carries the commit;
  2. else Chromium's official source tarball of a release whose DEPS pins
     that commit (the recorded release, or the pin's, for the base; the new
     tag's for theirs). One stream per release keeps only the files asked
     for, under <cache>/deps/tarball/<version>/, and only once the whole
     tarball matched its SHA-256 in tools/compile_check/ccheck/tarball.py
     (PINNED_SHA256): pin the new release's tarball before the rebase.
"""
import collections
import http.client
import json
import lzma
import re
import shutil
import sys
import tarfile
import time
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import upstream as up  # noqa: E402

sys.path.insert(0, str(up.REPO_ROOT / "tools" / "compile_check"))
from ccheck import tarball as cctarball  # noqa: E402

# DEPS subproject (its path in chromium/src) -> git mirrors that carry the
# commits Chromium's release branches pin, tried in order. WebRTC's and
# PDFium's GitHub mirrors stop at their main branch, and search_engines_data
# has none: those come from the release tarball.
MIRRORS = {
    "v8": ("https://github.com/v8/v8",),
    "third_party/skia": ("https://github.com/google/skia",),
}

_ENTRY_RE = re.compile(r"^(\S[^\t#]*?)\s+#\s+(\S+)@([0-9a-f]{40})"
                       r"(?:\s+\((\d+\.\d+\.\d+\.\d+)\))?\s*$")

# One whole_files.txt entry: the subproject's path in chromium/src, the
# subproject commit the file was last merged with, and a Chromium release
# whose DEPS pins that commit (its tarball has the merge base; None if not
# known).
WholeFile = collections.namedtuple("WholeFile", "subproject commit release")


class Unavailable(RuntimeError):
    """No mirror or verified tarball has the subproject at that commit."""


# ---------------------------------------------------------------------------
# patches/whole_files.txt


def read_whole_files(path=None):
    """{overlay path: WholeFile}. An entry without a recorded commit has
    WholeFile(None, None, None)."""
    path = up.WHOLE_FILES if path is None else path
    out = {}
    if not Path(path).exists():
        return out
    for line in Path(path).read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        m = _ENTRY_RE.match(line)
        if m:
            out[m.group(1)] = WholeFile(m.group(2), m.group(3), m.group(4))
        else:
            out[re.split(r"\s#", line, maxsplit=1)[0].strip()] = \
                WholeFile(None, None, None)
    return out


def whole_files_text(pin, entries):
    """whole_files.txt for `entries` {path: WholeFile}."""
    def entry(p):
        w = entries[p]
        return "%s\t# %s@%s%s\n" % (p, w.subproject, w.commit,
                                    " (%s)" % w.release if w.release else "")
    return ("# Generated by tools/chromium/overlay_to_patches.py - do not "
            "edit.\n# Upstream base: chromium/src@%s (%s)\n"
            "# Upstream files inside DEPS subprojects (separate repos), kept "
            "as whole-file\n# overlays. Each records the subproject commit "
            "it was last merged with (the\n# base of its next 3-way merge: "
            "tools/chromium/rebase.py) and a release\n# whose DEPS pins that "
            "commit.\n" % (pin.revision, pin.version)
            + "".join(entry(p) for p in sorted(entries)))


def write_whole_files(pin, entries, path=None):
    Path(up.WHOLE_FILES if path is None else path).write_text(
        whole_files_text(pin, entries))


def kept_entry(rec, link, pin_version):
    """The entry overlay_to_patches.py writes for a whole file inside the
    subproject `link` (subproject, commit) at the pin: the recorded one,
    kept as it is (only rebase.py moves it), or for a new file the pin's."""
    if rec and rec.commit and rec.subproject == link[0]:
        release = rec.release or (pin_version if rec.commit == link[1]
                                  else None)
        return WholeFile(rec.subproject, rec.commit, release)
    return WholeFile(link[0], link[1], pin_version)


def behind(chromium, commit, recorded):
    """[(path, WholeFile, gitlink at `commit` or None)] for whole files
    whose recorded subproject commit is not the gitlink at `commit`."""
    out = []
    for path, rec in sorted(recorded.items()):
        link = chromium.gitlink_for(commit, path)
        if link is None or (rec.subproject, rec.commit) != tuple(link):
            out.append((path, rec, link))
    return out


