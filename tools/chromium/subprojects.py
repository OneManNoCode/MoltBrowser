# Upstream content of subproject files


def mirror_cache_name(remote):
    """github.com/v8/v8 -> v8_v8 (a directory name)."""
    tail = remote.rstrip("/").split("://", 1)[-1].split("/", 1)[-1]
    tail = re.sub(r"\.git$", "", tail)
    return re.sub(r"[^A-Za-z0-9._-]", "_", tail)


def extract_paths(url, version, wanted, dest, log=up.log, opener=None,
                  pins=None):
    """Streams the release tarball at `url` once and keeps the regular files
    whose chromium/src path is in `wanted`, under dest/. Writes
    dest/manifest.json: {"version", "url", "sha256", "wanted", "found":
    {path: blob id}}. Built in a temporary directory and moved to `dest` only
    once the whole tarball matched its pinned SHA-256 (else
    cctarball.TarballNotVerified, and nothing is left behind)."""
    expected = cctarball.pinned_sha256(url, pins)
    dest = Path(dest)
    tmp = dest.with_name(dest.name + ".partial")
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    top = "chromium-%s/" % version
    wanted = set(wanted)
    found = {}
    t0 = time.time()
    log("tarball: streaming %s for %d file(s) (a few minutes)"
        % (url, len(wanted)))
    opener = opener or urllib.request.urlopen
    with opener(url) as r:
        hashed = cctarball.HashingReader(r)
        with tarfile.open(fileobj=hashed, mode="r|xz") as tf:
            for m in tf:
                if not m.isfile() or not m.name.startswith(top):
                    continue
                rel = m.name[len(top):]
                if rel not in wanted or cctarball.safe_relpath(rel) is None:
                    continue
                data = tf.extractfile(m).read()
                out = tmp / rel
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_bytes(data)
                found[rel] = up.blob_id(data)
        got = hashed.drain()
    if got != expected:
        shutil.rmtree(tmp, ignore_errors=True)
        raise cctarball.TarballNotVerified(
            "%s: SHA-256 %s, not the pinned %s" % (url, got, expected))
    (tmp / "manifest.json").write_text(json.dumps(
        {"version": version, "url": url, "sha256": got,
         "wanted": sorted(wanted), "found": found}, indent=1, sort_keys=True))
    shutil.rmtree(dest, ignore_errors=True)
    tmp.rename(dest)
    log("tarball: %d of %d file(s) found, %.0f s"
        % (len(found), len(wanted), time.time() - t0))
    return dest


class Sources:
    """Files of DEPS subprojects at given commits. Call want() for every
    (subproject, commit, files) needed, then fetch() once (each tarball is
    streamed at most once), then get()."""

    def __init__(self, cache_dir, offline=False, mirrors=None, log=up.log,
                 tarball_opener=None, tarball_pins=None):
        self.root = Path(cache_dir) / "deps"
        self.offline = offline
        self.mirrors = MIRRORS if mirrors is None else mirrors
        self.log = log
        self.tarball_opener = tarball_opener
        self.tarball_pins = tarball_pins
        self._wanted = {}   # (subproject, commit) -> {"paths", "releases"}
        self._got = {}      # (subproject, commit) -> ({inner: data}, how)
        self._why = {}      # (subproject, commit) -> [reason]

    def want(self, subproject, commit, inner_paths, releases=()):
        """`releases`: Chromium versions whose DEPS pin subproject@commit
        (their tarballs are the fallback)."""
        w = self._wanted.setdefault((subproject, commit),
                                    {"paths": set(), "releases": []})
        w["paths"].update(inner_paths)
        for v in releases:
            if v not in w["releases"]:
                w["releases"].append(v)

    def _from_mirror(self, key, paths):
        subproject, commit = key
        for remote in self.mirrors.get(subproject, ()):
            repo = up.Upstream(self.root / mirror_cache_name(remote), remote,
                               self.offline, name="mirror.git")
            try:
                c = repo.resolve(commit)
                tree = repo.tree(c)
                oids = {p: tree[p].oid for p in paths
                        if p in tree and tree[p].type == "blob"}
                blobs = repo.blobs(oids.values())
            except (RuntimeError, SystemExit) as e:
                # SystemExit: --offline and not cached (upstream.die).
                self._why.setdefault(key, []).append(
                    "%s: %s" % (remote, str(e).strip()[:300] or "offline"))
                continue
            return ({p: (blobs[oids[p]] if p in oids else None)
                     for p in paths}, "mirror " + remote)
        return None

    def _tarball_dir(self, version):
        return self.root / "tarball" / version

    def _from_tarballs(self, pending):
        """pending: {key: paths}. Groups by release, one stream each."""
        by_release = {}
        for key, paths in pending.items():
            rels = self._wanted[key]["releases"]
            if not rels:
                self._why.setdefault(key, []).append(
                    "no release tarball pins %s@%s" % key)
                continue
            by_release.setdefault(rels[0], {})[key] = paths
        for version, keys in sorted(by_release.items()):
            need = {"%s/%s" % (k[0], p) for k, ps in keys.items() for p in ps}
            dest = self._tarball_dir(version)
            url = cctarball.tarball_url(version, {"lite"})
            manifest = {}
            try:
                manifest = json.loads((dest / "manifest.json").read_text())
            except (OSError, ValueError):
                manifest = {}
            try:
                pinned = cctarball.pinned_sha256(url, self.tarball_pins)
            except cctarball.TarballNotVerified as e:
                for k in keys:
                    self._why.setdefault(k, []).append(str(e))
                continue
            cached = (manifest.get("sha256") == pinned and
                      need <= set(manifest.get("wanted", ())))
            if not cached:
                if self.offline:
                    for k in keys:
                        self._why.setdefault(k, []).append(
                            "%s is not cached and --offline was given" % url)
                    continue
                try:
                    extract_paths(url, version,
                                  need | set(manifest.get("wanted", ())),
                                  dest, self.log, self.tarball_opener,
                                  self.tarball_pins)
                    manifest = json.loads(
                        (dest / "manifest.json").read_text())
                except (OSError, EOFError, http.client.HTTPException,
                        lzma.LZMAError, tarfile.TarError,
                        cctarball.TarballNotVerified) as e:
                    for k in keys:
                        self._why.setdefault(k, []).append(
                            "%s: %s" % (url, e))
                    continue
            found = manifest.get("found", {})
            for k, ps in keys.items():
                files = {}
                for p in ps:
                    rel = "%s/%s" % (k[0], p)
                    files[p] = ((dest / rel).read_bytes() if rel in found
                                else None)
                self._got[k] = (files, "tarball chromium-%s" % version)

    def fetch(self):
        pending = {}
        for key, w in sorted(self._wanted.items()):
            have = self._got.get(key)
            if have and w["paths"] <= set(have[0]):
                continue
            got = self._from_mirror(key, sorted(w["paths"]))
            if got:
                self._got[key] = got
            else:
                pending[key] = sorted(w["paths"])
        if pending:
            self._from_tarballs(pending)

    def get(self, subproject, commit, inner):
        """The file's bytes at subproject@commit, None if it doesn't exist
        there; Unavailable if neither a mirror nor a tarball had it."""
        have = self._got.get((subproject, commit))
        if have is None or inner not in have[0]:
            raise Unavailable("; ".join(self._why.get(
                (subproject, commit), ["not fetched"])))
        return have[0][inner]

    def source(self, subproject, commit):
        have = self._got.get((subproject, commit))
        return have[1] if have else None
