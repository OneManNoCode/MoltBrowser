"""Checks that MoltNet's bundled fonts measure alike on Linux, Windows and
macOS: runs Blink's metric code with each OS's #if branches over the real
bundled fonts.

What runs (no Chromium checkout needed):
  1. skrifa_dump (Rust, the skrifa version Chromium 156 vendors) reads every
     face of the set at several sizes and weights and writes what Skia's
     Fontations backend reports: SkFontMetrics, and per sample glyph its
     advance and path bounds.
  2. The functions between SkFont and a SimpleFontData's metrics whose
     result depends on the OS (FontMetrics::AscentDescentWithHacks,
     SimpleFontData::PlatformInit, the glyph bounds and HarfBuzz extents of
     skia_text_metrics.cc) are copied verbatim out of src/, MoltBrowser's
     hooks included, and built three times, as Linux, Windows and macOS, with
     g++ and clang++ (ASan/UBSan), on stand-ins that carry step 1's values
     (harness.cc, standins.h).
  3. With the set active every value must be the same on the three OSes,
     and on Linux the same as without it; without the set the OSes differ
     (upstream). Each hook, removed, must make the OSes disagree.

  python3 tools/fonts/metrics_check/run.py [--fonts DIR] [--out DIR]

--fonts: a folder with the set installed (scripts/bundle-fonts.sh --dest);
by default the set is installed from the fetch cache (tools/fonts/
fetch_fonts.py downloads what is missing). Needs cargo (crates.io reachable
the first time), g++ and clang++. Run it after rebasing onto a new Chromium
or updating the set. Exit status 0 when every check passes.
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE =os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
FONTS_SRC = os.path.join(REPO, "src", "third_party", "blink", "renderer",
                         "platform", "fonts")
sys.path.insert(0, os.path.dirname(HERE))
import fetch_fonts  # noqa: E402
import manifest as mf  # noqa: E402

OSES = ("LINUX", "WIN", "MAC")
COMPILERS = (("g++", ["-fsanitize=address,undefined"]),
             ("clang++", ["-fsanitize=address,undefined",
                          "-fno-sanitize-recover=all"]))
# Each hook, and what removing it looks like in the extracted code.
MUTANTS = {
    "descent rule outside Linux": (
        "if (FontPlatformData::GetUniformFontSet() && descent < metrics.fDescent",
        "if (false && descent < metrics.fDescent"),
    "macOS x-height measured": (
        "FontPlatformData::GetUniformFontSet() ? 0 : GlyphForCharacter('x')",
        "GlyphForCharacter('x')"),
    "per-OS maximum width": (
        "if (FontPlatformData::GetUniformFontSet()) {\n    max_char_width_",
        "if (false) {\n    max_char_width_"),
    "macOS average width": (
        "if (FontPlatformData::GetUniformFontSet() && metrics.fAvgCharWidth)",
        "if (false && metrics.fAvgCharWidth)"),
    "macOS path bounds": (
        "if (!FontPlatformData::GetUniformFontSet()) {\n    GetPathBoundsForGlyph",
        "if (true) {\n    GetPathBoundsForGlyph"),
    "macOS HarfBuzz extents": (
        "if (FontPlatformData::GetUniformFontSet()) {\n    sk_bounds = font.getBounds",
        "if (false) {\n    sk_bounds = font.getBounds"),
}


# --- 2. The code under test ----------------------------------------------------

def _function(text, signature):
    """The definition starting at the line that starts with `signature`, up
    to the first line that is exactly "}"."""
    start = text.index("\n" + signature) + 1
    end = text.index("\n}\n", start) + 3
    return text[start:end]


def _region(text, first, last):
    start = text.index(first)
    end = text.index(last, start) + len(last)
    return text[start:end] + "\n"


def extract():
    def read(name):
        with open(os.path.join(FONTS_SRC, name), encoding="utf-8") as f:
            return f.read()
    metrics = read("font_metrics.cc")
    simple = read("simple_font_data.cc")
    skia = read(os.path.join("skia", "skia_text_metrics.cc"))
    return "\n".join([
        "// GENERATED by tools/fonts/metrics_check/run.py from src/.",
        "// font_metrics.cc",
        _region(metrics, "#if BUILDFLAG(IS_LINUX) || BUILDFLAG(IS_CHROMEOS) || "
                "BUILDFLAG(IS_ANDROID) || \\\n    BUILDFLAG(IS_FUCHSIA)\n// This "
                "is the largest VDMX", "#endif"),
        _function(metrics, "void FontMetrics::AscentDescentWithHacks("),
        "// skia/skia_text_metrics.cc",
        _function(skia, "void SkFontGetGlyphExtentsForHarfBuzz("),
        _region(skia, "#if BUILDFLAG(IS_APPLE)\nstatic void GetPathBoundsForGlyph",
                "#endif"),
        _function(skia, "void SkFontGetBoundsForGlyph("),
        _function(skia, "float SkFontGetWidthForGlyph("),
        "// simple_font_data.cc",
        _function(simple, "void SimpleFontData::PlatformInit("),
        _function(simple, "gfx::RectF SimpleFontData::PlatformBoundsForGlyph("),
        _function(simple, "float SimpleFontData::WidthForGlyph("),
    ])


# --- 1. What Fontations reports ------------------------------------------------

def install_fonts(dest):
    cache = Path(os.environ.get("MOLT_FONTS_CACHE",
                                str(fetch_fonts.DEFAULT_CACHE)))
    fetch_fonts.install(mf.load(), dest, cache, offline=False)
    return dest


def dump(fonts, out):
    target = os.path.join(out, "cargo")
    subprocess.run(["cargo", "build", "--release", "--quiet", "--manifest-path",
                    os.path.join(HERE, "skrifa_dump", "Cargo.toml"),
                    "--target-dir", target], check=True)
    names = [e["install_name"] for e in mf.load()["files"]]
    cases = subprocess.run(
        [os.path.join(target, "release", "skrifa_dump"), fonts] + names,
        stdout=subprocess.PIPE, check=True).stdout.decode()
    path = os.path.join(out, "cases.txt")
    with open(path, "w") as f:
        f.write(cases)
    tables = [line.split()[1] for line in cases.splitlines()
              if " trak=1" in line or " sbix=1" in line]
    return path, len(cases.splitlines()), sorted(set(tables))


# --- 3. The comparison ---------------------------------------------------------

def build(directory, compiler, flags, os_name, name):
    binary = os.path.join(directory, name)
    subprocess.run([compiler, "-std=c++20", "-O1", "-g", "-Wall", "-Wextra",
                    "-Wno-unused-parameter", "-Wno-unused-variable",
                    "-fno-exceptions", "-DMOLT_OS_" + os_name, "-I", directory,
                    "-I", HERE] + flags +
                   [os.path.join(HERE, "harness.cc"), "-o", binary],
                   check=True)
    return binary


def run(binary, cases, mode):
    return subprocess.run([binary, cases, mode], stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, check=True).stdout


def _labels_that_differ(a, b):
    names, label = [], ""
    for x, y in zip(a.split(), b.split()):
        value = x.lstrip("-")
        if not value.startswith("0x") and not value.isdigit():
            label = x
        if x != y:
            names.append(label)
    return names


def compare(out, cases):
    ok = True
    for compiler, flags in COMPILERS:
        binaries = {o: build(out, compiler, flags, o,
                             "harness_%s_%s" % (compiler.strip("+"), o.lower()))
                    for o in OSES}
        results = {}
        for mode in ("uniform", "system"):
            results[mode] = {o: run(binaries[o], cases, mode).decode()
                             .splitlines() for o in OSES}
            linux = results[mode]["LINUX"]
            for other in ("WIN", "MAC"):
                lines = results[mode][other]
                differ = [i for i in range(len(linux)) if linux[i] != lines[i]]
                kinds = {}
                for i in differ:
                    for label in _labels_that_differ(linux[i], lines[i]):
                        kinds[label] = kinds.get(label, 0) + 1
                print("%s, set %s: Linux vs %s: %d of %d cases differ %s" % (
                    compiler, "active" if mode == "uniform" else "not active",
                    other, len(differ), len(linux),
                    ", ".join("%s:%d" % kv for kv in sorted(kinds.items()))))
                if mode == "uniform" and differ:
                    ok = False
        same = results["uniform"]["LINUX"] == results["system"]["LINUX"]
        print("%s: Linux with the set as without: %s" % (
            compiler, "yes" if same else "NO"))
        ok = ok and same
    return ok


def mutants(out, cases):
    base = open(os.path.join(out, "extracted.inc")).read()
    caught = 0
    for name, (old, new) in MUTANTS.items():
        if base.count(old) != 1:
            print("mutant %s: the hook text is not in the code" % name)
            continue
        directory = os.path.join(out, "mutant")
        shutil.rmtree(directory, ignore_errors=True)
        os.makedirs(directory)
        with open(os.path.join(directory, "extracted.inc"), "w") as f:
            f.write(base.replace(old, new))
        outputs = {run(build(directory, "clang++", ["-w"], o, "h_" + o), cases,
                       "uniform") for o in OSES}
        caught += len(outputs) > 1
        print("without the hook '%s': %s" % (
            name, "the OSes disagree" if len(outputs) > 1 else "NOT NOTICED"))
    return caught == len(MUTANTS)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--fonts", help="the installed set")
    parser.add_argument("--out", help="working folder (default: a temporary "
                                      "one)")
    args = parser.parse_args(argv)
    out = args.out or tempfile.mkdtemp(prefix="molt-metrics-")
    os.makedirs(out, exist_ok=True)
    fonts = args.fonts or install_fonts(os.path.join(out, "molt_fonts"))
    with open(os.path.join(out, "extracted.inc"), "w") as f:
        f.write(extract())
    cases, count, with_tables = dump(fonts, out)
    print("%d cases (faces x weights x sizes) from %s" % (count, fonts))
    # macOS takes HarfBuzz's advances for a face with 'trak' and no 'sbix'
    # (harfbuzz_face.cc): the set must have none.
    print("faces with 'trak' or 'sbix': %s" % (with_tables or "none"))
    ok = not with_tables
    ok = compare(out, cases) and ok
    ok = mutants(out, cases) and ok
    print("MoltNet's bundled fonts measure alike on Linux, Windows and macOS: "
          "%s (working folder %s)" % ("yes" if ok else "NO", out))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
